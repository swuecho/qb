(* SQL rendering tests, then the same database tests on SQLite and, when
   QB_TEST_PG_URL is set, on Postgres (see scripts/test-pg.sh). *)

open Qb

module Users = struct
  type t = { id : int; name : string; age : int; email : string option }

  let id =
    column "id" int (fun u -> u.id) ~primary_key:true ~auto_increment:true

  let name = column "name" text (fun u -> u.name)
  let age = column "age" int (fun u -> u.age)
  let email = column "email" (nullable text) (fun u -> u.email)

  let table =
    table "users"
      (let+ id = col id
       and+ name = col name
       and+ age = col age
       and+ email = col email in
       { id; name; age; email })
end

(* Every column type, to check each one round-trips. *)
module Things = struct
  type t = {
    id : int;
    big : int64;
    ratio : float;
    flag : bool;
    blob : string;
    at : Ptime.t;
    day : Ptime.t;
    uid : string;
    doc : string;
  }

  let id = column "id" int (fun t -> t.id) ~primary_key:true
  let big = column "big" int64 (fun t -> t.big)
  let ratio = column "ratio" float (fun t -> t.ratio)
  let flag = column "flag" bool (fun t -> t.flag)
  let blob = column "blob" octets (fun t -> t.blob)
  let at = column "at" ptime (fun t -> t.at)
  let day = column "day" date (fun t -> t.day)
  let uid = column "uid" uuid (fun t -> t.uid)
  let doc = column "doc" json (fun t -> t.doc)

  let table =
    table "things"
      (let+ id = col id
       and+ big = col big
       and+ ratio = col ratio
       and+ flag = col flag
       and+ blob = col blob
       and+ at = col at
       and+ day = col day
       and+ uid = col uid
       and+ doc = col doc in
       { id; big; ratio; flag; blob; at; day; uid; doc })
end

(* Names that are SQL keywords must be quoted to work at all. *)
module Order = struct
  type t = { user : int; group : string option }

  let user = column "user" int (fun o -> o.user) ~primary_key:true
  let group = column "group" (nullable text) (fun o -> o.group)

  let table =
    table "order"
      (let+ user = col user and+ group = col group in
       { user; group })
end

(* For joins: comments by users, and replies to comments. *)
module Comments = struct
  type t = { id : int; author_id : int; body : string; reply_to : int option }

  let id = column "id" int (fun c -> c.id) ~primary_key:true
  let author_id = column "author_id" int (fun c -> c.author_id)
  let body = column "body" text (fun c -> c.body)
  let reply_to = column "reply_to" (nullable int) (fun c -> c.reply_to)

  let table =
    table "comments"
      (let+ id = col id
       and+ author_id = col author_id
       and+ body = col body
       and+ reply_to = col reply_to in
       { id; author_id; body; reply_to })
end

(* For changesets: created as SQL (see [create_signups]) for its UNIQUE,
   CHECK and FOREIGN KEY constraints. *)
module Signups = struct
  type t = { id : int; email : string; age : int; owner_id : int option }

  let id =
    column "id" int (fun a -> a.id) ~primary_key:true ~auto_increment:true

  let email = column "email" text (fun a -> a.email)
  let age = column "age" int (fun a -> a.age)
  let owner_id = column "owner_id" (nullable int) (fun a -> a.owner_id)

  let table =
    table "signups"
      (let+ id = col id
       and+ email = col email
       and+ age = col age
       and+ owner_id = col owner_id in
       { id; email; age; owner_id })
end

