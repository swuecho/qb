module type DB = Caqti_blocking.CONNECTION

let drop (module Db : DB) name =
  ok
    (Db.exec
       (Caqti_request.Infix.(Caqti_type.unit ->. Caqti_type.unit)
          (Printf.sprintf {|DROP TABLE IF EXISTS "%s"|} name))
       ())

(* Each test gets fresh tables. *)
let with_db url f () =
  let db = ok (Caqti_blocking.connect (Uri.of_string url)) in
  let (module Db : DB) = db in
  Fun.protect ~finally:Db.disconnect @@ fun () ->
  List.iter (drop db)
    [ "signups"; "users"; "things"; "order"; "tickets"; "comments" ];
  List.iter ok
    [
      Blocking.create_table db Users.table;
      Blocking.create_table db Things.table;
      Blocking.create_table db Order.table;
      Blocking.create_table db Tickets.table;
      Blocking.create_table db Comments.table;
    ];
  f db

