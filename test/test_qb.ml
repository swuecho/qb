let test_conditions () =
  let q c = from Users.table |> select (col Users.id) |> where c in
  check_sql "= None is IS NULL"
    {|SELECT "id" FROM "users" WHERE "email" IS NULL|}
    (q Ops.(Users.email = None));
  check_sql "<> None is IS NOT NULL"
    {|SELECT "id" FROM "users" WHERE "email" IS NOT NULL|}
    (q Ops.(Users.email <> None));
  check_sql "empty IN matches nothing" {|SELECT "id" FROM "users" WHERE 1 = 0|}
    (q Ops.(is_in Users.id []));
  check_sql "IN, LIKE, OR, NOT"
    {|SELECT "id" FROM "users" WHERE ("id" IN (?, ?) OR NOT ("name" LIKE ?))|}
    (q Ops.(is_in Users.id [ 1; 2 ] || not (like Users.name "A%")));
  check_sql "all_rows renders no WHERE" {|SELECT "id" FROM "users"|}
    (q all_rows);
  check_sql "all_rows then a condition keeps only the condition"
    {|SELECT "id" FROM "users" WHERE "age" < ?|}
    (q all_rows |> where Ops.(Users.age < 18));
  check_sql "a nullable column against a plain value"
    {|SELECT "id" FROM "users" WHERE ("email" = ? AND "email" IS NOT NULL)|}
    (q Ops.(Users.email =? "a@x.org" && is_not_null Users.email));
  check_sql "like on a nullable column"
    {|SELECT "id" FROM "users" WHERE ("email" LIKE ? OR "email" ILIKE ?)|}
    (q Ops.(like_opt Users.email "%@x.org" || ilike_opt Users.email "ANN%"));
  check_sql "is_null" {|SELECT "id" FROM "users" WHERE "email" IS NULL|}
    (q Ops.(is_null Users.email));
  check_sql "between, not_in"
    {|SELECT "id" FROM "users" WHERE (("age" >= ? AND "age" <= ?) AND NOT ("id" IN (?, ?)))|}
    (q Ops.(between Users.age 18 65 && not_in Users.id [ 1; 2 ]));
  check_sql "ilike on Postgres"
    {|SELECT "id" FROM "users" WHERE "name" ILIKE ?|}
    (q Ops.(ilike Users.name "a%"));
  Alcotest.(check string)
    "ilike elsewhere"
    {|SELECT "id" FROM "users" WHERE LOWER("name") LIKE LOWER(?)|}
    (to_sql ~dialect:Sqlite (q Ops.(ilike Users.name "a%")));
  let adults = from Users.table |> where Ops.(Users.age >= 18) in
  Alcotest.(check string)
    "insert_many"
    {|INSERT INTO "users" ("id", "name", "age", "email") VALUES (?, ?, ?, ?), (?, ?, ?, ?)|}
    (insert_many_sql Users.table
       [
         { id = 1; name = "a"; age = 1; email = None };
         { id = 2; name = "b"; age = 2; email = None };
       ]);
  Alcotest.(check string)
    "update returning"
    {|UPDATE "users" SET "age" = ? WHERE "age" >= ? RETURNING "id", "age"|}
    (update_returning_sql Ops.[ Users.age := 1 ] adults [ Users.id; Users.age ]);
  Alcotest.(check string)
    "delete returning a whole row"
    {|DELETE FROM "users" WHERE "age" >= ? RETURNING "id", "name", "age", "email"|}
    (delete_returning_sql adults
       (let+ id = col Users.id
        and+ name = col Users.name
        and+ age = col Users.age
        and+ email = col Users.email in
        { Users.id; name; age; email }))

