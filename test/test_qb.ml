let test_select () =
  check_sql "whole rows" {|SELECT "id", "name", "age", "email" FROM "users"|}
    (from Users.table);
  check_sql "where, order, limit, offset"
    {|SELECT "id", "name" FROM "users" WHERE ("age" > ? AND "name" <> ?) ORDER BY "name" ASC, "id" DESC LIMIT 10 OFFSET 20|}
    (from Users.table
    |> where Ops.(Users.age > 18)
    |> where Ops.(Users.name <> "Bob")
    |> select
         (let+ id = col Users.id and+ name = col Users.name in
          (id, name))
    |> order_by [ asc Users.name; desc Users.id ]
    |> limit 10 |> offset 20);
  Alcotest.(check string)
    "offset without limit on Postgres" {|SELECT "id" FROM "users" OFFSET 5|}
    (to_sql ~dialect:Postgres
       (from Users.table |> select [ Users.id ] |> offset 5));
  Alcotest.(check string)
    "offset without limit on SQLite"
    {|SELECT "id" FROM "users" LIMIT -1 OFFSET 5|}
    (to_sql ~dialect:Sqlite
       (from Users.table |> select [ Users.id ] |> offset 5));
  Alcotest.(check string)
    "offset without limit on MySQL"
    "SELECT `id` FROM `users` LIMIT 18446744073709551615 OFFSET 5"
    (to_sql ~dialect:Mysql
       (from Users.table |> select [ Users.id ] |> offset 5));
  Alcotest.check_raises "negative limit"
    (Invalid_argument "Qb.limit: negative limit") (fun () ->
      ignore (from Users.table |> limit (-1)));
  Alcotest.check_raises "negative offset"
    (Invalid_argument "Qb.offset: negative offset") (fun () ->
      ignore (from Users.table |> offset (-1)));
  check_sql "distinct" {|SELECT DISTINCT "age" FROM "users"|}
    (from Users.table |> select (col Users.age) |> distinct);
  check_sql "nulls_first and nulls_last on Postgres"
    {|SELECT "id" FROM "users" ORDER BY "email" ASC NULLS FIRST, "age" DESC NULLS LAST|}
    (from Users.table |> select [ Users.id ]
    |> order_by [ asc Users.email |> nulls_first; desc Users.age |> nulls_last ]
    );
  Alcotest.(check string)
    "nulls_first and nulls_last on SQLite"
    {|SELECT "id" FROM "users" ORDER BY "email" ASC NULLS FIRST, "age" DESC NULLS LAST|}
    (to_sql ~dialect:Sqlite
       (from Users.table |> select [ Users.id ]
       |> order_by
            [ asc Users.email |> nulls_first; desc Users.age |> nulls_last ]));
  Alcotest.(check string)
    "nulls_first and nulls_last on MySQL"
    "SELECT `id` FROM `users` ORDER BY `email` IS NULL DESC, `email` ASC, \
     `age` IS NULL ASC, `age` DESC"
    (to_sql ~dialect:Mysql
       (from Users.table |> select [ Users.id ]
       |> order_by
            [ asc Users.email |> nulls_first; desc Users.age |> nulls_last ]));
  Alcotest.(check string)
    "insert_many_values homogeneous"
    {|INSERT INTO "users" ("name", "age") VALUES (?, ?), (?, ?) RETURNING "id", "name", "age", "email"|}
    (insert_many_values_sql
       [
         values Users.table Ops.[ Users.name := "Ann"; Users.age := 34 ];
         values Users.table Ops.[ Users.name := "Bob"; Users.age := 51 ];
       ]);
  Alcotest.(check string)
    "insert_many_values heterogeneous uses DEFAULT on Postgres"
    {|INSERT INTO "users" ("name", "age", "email") VALUES (?, ?, DEFAULT), (?, ?, ?) RETURNING "id", "name", "age", "email"|}
    (insert_many_values_sql
       [
         values Users.table Ops.[ Users.name := "Ann"; Users.age := 34 ];
         values Users.table
           Ops.
             [ Users.name := "Bob"; Users.age := 51; Users.email := Some "b@x" ];
       ]);
  Alcotest.check_raises "insert_many_values heterogeneous rejected on SQLite"
    (Invalid_argument
       "Qb.insert_many_values: on SQLite every row must set the same columns")
    (fun () ->
      ignore
        (insert_many_values_sql ~dialect:Sqlite
           [
             values Users.table Ops.[ Users.name := "Ann"; Users.age := 34 ];
             values Users.table
               Ops.
                 [
                   Users.name := "Bob";
                   Users.age := 51;
                   Users.email := Some "b@x";
                 ];
           ]));
  Alcotest.(check string)
    "insert_many_values all-default rows on Postgres"
    {|INSERT INTO "tickets" ("id") VALUES (DEFAULT), (DEFAULT) RETURNING "id"|}
    (insert_many_values_sql
       [ values Tickets.table []; values Tickets.table [] ]);
  Alcotest.check_raises "insert_many_values_sql empty"
    (Invalid_argument "Qb.insert_many_values_sql: no rows") (fun () ->
      ignore (insert_many_values_sql []));
  Alcotest.(check string)
    "upsert do nothing"
    {|INSERT INTO "users" ("id", "name", "age") VALUES (?, ?, ?) ON CONFLICT DO NOTHING RETURNING "id", "name", "age", "email"|}
    (upsert_sql
       (On_conflict.do_nothing ())
       (values Users.table
          Ops.[ Users.id := 1; Users.name := "Ann"; Users.age := 34 ]));
  Alcotest.(check string)
    "upsert do update with excluded, set, and qualified where"
    {|INSERT INTO "users" ("id", "name", "age") VALUES (?, ?, ?) ON CONFLICT ("id") DO UPDATE SET "name" = EXCLUDED."name", "age" = ? WHERE "users"."age" < ? RETURNING "id", "name", "age", "email"|}
    (upsert_sql
       On_conflict.(
         do_update
           ~target:[ col Users.id ]
           ~excluded:[ col Users.name ]
           ~set:Ops.[ Users.age := 40 ]
           ~where:Ops.(Users.age < 50)
           ())
       (values Users.table
          Ops.[ Users.id := 1; Users.name := "Ann"; Users.age := 34 ]));
  Alcotest.(check string)
    "upsert_many_sql"
    {|INSERT INTO "users" ("id", "name", "age") VALUES (?, ?, ?), (?, ?, ?) ON CONFLICT ("id") DO UPDATE SET "name" = EXCLUDED."name", "age" = EXCLUDED."age" RETURNING "id", "name", "age", "email"|}
    (upsert_many_sql
       On_conflict.(
         do_update
           ~target:[ col Users.id ]
           ~excluded:[ col Users.name; col Users.age ]
           ())
       [
         values Users.table
           Ops.[ Users.id := 1; Users.name := "Ann"; Users.age := 34 ];
         values Users.table
           Ops.[ Users.id := 2; Users.name := "Bob"; Users.age := 51 ];
       ]);
  Alcotest.check_raises "do_update empty target"
    (Invalid_argument "Qb.On_conflict.do_update: target must not be empty")
    (fun () ->
      ignore On_conflict.(do_update ~target:[] ~excluded:[ col Users.name ] ()));
  Alcotest.check_raises "do_update empty set and excluded"
    (Invalid_argument
       "Qb.On_conflict.do_update: give at least one column in ~set or ~excluded")
    (fun () -> ignore On_conflict.(do_update ~target:[ col Users.id ] ()));
  Alcotest.check_raises "upsert_many_sql empty"
    (Invalid_argument "Qb.upsert_many_sql: no rows") (fun () ->
      ignore (upsert_many_sql (On_conflict.do_nothing ()) []));
  (* where_opt, Ops.all_of, Ops.any_of *)
  Alcotest.(check string)
    "where_opt None is a no-op"
    {|SELECT "id", "name", "age", "email" FROM "users"|}
    (to_sql (from Users.table |> where_opt None));
  Alcotest.(check string)
    "where_opt + all_of + any_of"
    {|SELECT "id", "name", "age", "email" FROM "users" WHERE (("age" >= ? AND "age" <= ?) AND ("name" = ? OR "name" = ?))|}
    (to_sql
       (from Users.table
       |> where_opt (Ops.all_of Ops.[ Users.age >= 18; Users.age <= 65 ])
       |> where_opt (Ops.any_of Ops.[ Users.name = "Ann"; Users.name = "Bob" ])
       ));
  Alcotest.(check bool) "all_of []" true (Ops.all_of [] = None);
  Alcotest.(check bool) "any_of []" true (Ops.any_of [] = None);
  (* Duplicate assignments keep the last value in first-seen column order. *)
  Alcotest.(check string)
    "dedup values assigns"
    {|INSERT INTO "users" ("name", "age") VALUES (?, ?) RETURNING "id", "name", "age", "email"|}
    (insert_values_sql
       (values Users.table
          Ops.[ Users.name := "A"; Users.age := 1; Users.name := "B" ]));
  Alcotest.(check string)
    "dedup update assigns"
    {|UPDATE "users" SET "name" = ?, "age" = ? WHERE "id" = ?|}
    (update_sql
       Ops.[ Users.name := "A"; Users.age := 1; Users.name := "B" ]
       (from Users.table |> where Ops.(Users.id = 1)));
  Alcotest.(check string)
    "dedup on_conflict set overrides excluded"
    {|INSERT INTO "users" ("id", "name") VALUES (?, ?) ON CONFLICT ("id") DO UPDATE SET "name" = ? RETURNING "id", "name", "age", "email"|}
    (upsert_sql
       On_conflict.(
         do_update
           ~target:[ col Users.id; col Users.id ]
           ~excluded:[ col Users.name ]
           ~set:Ops.[ Users.name := "Fixed" ]
           ())
       (values Users.table Ops.[ Users.id := 1; Users.name := "Ann" ]));
  (* Stmt placeholder validation for all statements *)
  Alcotest.check_raises "stmt $2 out of bounds"
    (Invalid_argument "Qb.Stmt (bad): $2 has no argument (1 given)") (fun () ->
      ignore
        (stmt_sql
           (Stmt.make ~name:"bad" "SELECT $1, $2" [ Stmt.arg int 1 ] Stmt.unit)));
  Alcotest.check_raises "stmt ? count mismatch"
    (Invalid_argument
       "Qb.Stmt (q): SQL has 2 ? placeholders but 1 argument was given")
    (fun () ->
      ignore
        (stmt_sql
           (Stmt.make ~name:"q" "SELECT ?, ?" [ Stmt.arg int 1 ] Stmt.unit)))

let test_join_sql () =
  check_sql
    "inner join: the left query carries over, the right's where joins the ON"
    {|SELECT "l"."body", "r"."id", "r"."name", "r"."age", "r"."email" FROM "comments" AS "l" JOIN "users" AS "r" ON ("l"."author_id" = "r"."id" AND "r"."age" > ?) WHERE "l"."id" > ? ORDER BY "l"."id" ASC LIMIT 5|}
    (from Comments.table
    |> where Ops.(Comments.id > 10)
    |> select [ Comments.body ]
    |> order_by [ asc Comments.id ]
    |> limit 5
    |> join Users.table
         ~on:Ops.(Comments.author_id == Users.id)
         ~where:Ops.(Users.age > 18));
  check_sql "left join, self"
    {|SELECT "l"."id", "l"."author_id", "l"."body", "l"."reply_to", "r"."id", "r"."author_id", "r"."body", "r"."reply_to" FROM "comments" AS "l" LEFT JOIN "comments" AS "r" ON "l"."reply_to" = "r"."id"|}
    (from Comments.table
    |> left_join Comments.table ~on:Ops.(Comments.reply_to == some Comments.id)
    );
  let before =
    from Comments.table
    |> where Ops.(Comments.id > 10)
    |> order_by [ asc Comments.id ]
    |> limit 5
    |> join Users.table ~on:Ops.(Comments.author_id == Users.id)
  and after =
    from Comments.table
    |> join Users.table ~on:Ops.(Comments.author_id == Users.id)
    |> where Ops.(Comments.id > 10)
    |> order_by [ asc Comments.id ]
    |> limit 5
  in
  Alcotest.(check string)
    "where and order_by after the join: same SQL" (to_sql before) (to_sql after);
  check_sql "where on both sides of the join"
    {|SELECT "l"."id", "l"."author_id", "l"."body", "l"."reply_to", "r"."id", "r"."name", "r"."age", "r"."email" FROM "comments" AS "l" JOIN "users" AS "r" ON "l"."author_id" = "r"."id" WHERE ("l"."id" > ? AND "l"."body" LIKE ?)|}
    (from Comments.table
    |> where Ops.(Comments.id > 10)
    |> join Users.table ~on:Ops.(Comments.author_id == Users.id)
    |> where Ops.(like Comments.body "%x%"))
(* select after a join, a second join, and update or delete through a join
   don't type-check (the query's 'w is _ * joined); see example/join.ml. *)

