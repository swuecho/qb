  Alcotest.(check error_list)
    "blank non-null"
    [ ("name", "can't be blank") ]
    (errors cs);
  Alcotest.(check (option (option string)))
    "blank nullable" (Some None)
    (C.get_change Users.email cs);
  Alcotest.check_raises "a type with no of_string"
    (Invalid_argument "Qb.Changeset.cast: column c has no of_string (see Qb.ty)")
    (fun () ->
      let c = column "c" (ty Caqti_type.ptime_span "INTERVAL") Fun.id in
      ignore
        C.(for_insert (table "t" (col c)) |> cast [ ("c", "1") ] [ field c ]))

let test_validate () =
  let cs = signup_changeset (C.for_insert Signups.table) [ ("owner_id", "") ] in
  Alcotest.(check error_list)
    "required"
    [ ("email", "can't be blank"); ("age", "can't be blank") ]
    (errors cs);
  let cs =
    signup_changeset
      (C.for_insert Signups.table)
      [ ("email", "日本"); ("age", "-1") ]
  in
  Alcotest.(check error_list)
    "rules, characters not bytes"
    [
      ("email", "should be at least 3 characters");
      ("email", "has invalid format");
      ("age", "must be greater than or equal to 0");
    ]
    (errors cs);
  Alcotest.(check bool)
    "kinds" true
    (List.map (fun (e : C.error) -> e.kind) (C.errors cs)
    = [ `Length; `Format; `Range ]);
  let cs =
    C.(
      for_insert Users.table |> put Users.name "root" |> put Users.age 3
      |> validate Users.name [ none_of [ "root" ]; length ~is:3 () ]
      |> validate Users.age
           [ one_of [ 1; 2 ]; check "must be even" (fun n -> n mod 2 = 0) ]
      |> validate_opt Users.email [ length ~max:1 () ])
  in
  Alcotest.(check error_list)
    "other rules"
    [
      ("name", "is reserved");
      ("name", "should be 3 characters");
      ("age", "is invalid");
      ("age", "must be even");
    ]
    (errors cs);
  Alcotest.(check (list string))
    "errors_on"
    [ "is invalid"; "must be even" ]
    (C.errors_on Users.age cs);
  (* An update: the row's values count, a same value is no change, and only
     changes are checked. *)
  let bad = { ann with age = 200 } in
  let cs =
    C.(
      for_update Users.table bad
      |> cast
           [ ("name", "Ann"); ("email", "new@x.org") ]
           [ field Users.name; field Users.email ]
      |> validate_required [ field Users.age ]
      |> validate Users.age [ range ~lt:150 () ])
  in
  Alcotest.(check error_list) "update" [] (errors cs);
  Alcotest.(check int) "only the email changed" 1 (List.length (C.changes cs));
  Alcotest.(check (option int))
    "get falls back to the row" (Some 200) (C.get Users.age cs);
  Alcotest.(check string) "input shows the value" "200" (C.input Users.age cs)

let create_signups ((module Db : DB) as db) =
  let sql =
    match Caqti_driver_info.dialect_tag Db.driver_info with
    | `Pgsql ->
        {|CREATE TABLE signups (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email TEXT NOT NULL UNIQUE,
            age BIGINT NOT NULL CHECK (age >= 0),
            owner_id BIGINT REFERENCES users (id))|}
    | _ ->
        ok
          (Db.exec
             Caqti_request.Infix.(
               (Caqti_type.unit ->. Caqti_type.unit) "PRAGMA foreign_keys = ON")
             ());
        {|CREATE TABLE signups (
            id INTEGER PRIMARY KEY,
            email TEXT NOT NULL UNIQUE,
            age INTEGER NOT NULL CONSTRAINT signups_age_check CHECK (age >= 0),
            owner_id INTEGER REFERENCES users (id))|}
  in
  ok
    (Db.exec Caqti_request.Infix.((Caqti_type.unit ->. Caqti_type.unit) sql) ());
  ignore db

let test_changeset_db db =
  seed db;
  create_signups db;
  let with_constraints cs =
    C.(
      cs
      |> unique_constraint Signups.email
      |> check_constraint Signups.age
      |> foreign_key_constraint Signups.owner_id)
  in
  let insert params =
    Blocking.insert_changeset db
      (with_constraints (signup_changeset (C.for_insert Signups.table) params))
  in
  let invalid = function
    | Error (`Invalid cs) -> errors cs
    | Ok _ -> Alcotest.fail "expected `Invalid, got Ok"
    | Error `Stale -> Alcotest.fail "expected `Invalid, got `Stale"
    | Error (#Caqti_error.t as e) -> Alcotest.fail (Caqti_error.show e)
  in
  let a =
    match insert [ ("email", "a@x.org"); ("age", "30"); ("owner_id", "1") ] with
    | Ok a -> a
    | Error _ -> Alcotest.fail "insert"
  in
  Alcotest.(check (pair string (option int)))
    "inserted, id filled in" ("a@x.org", Some 1) (a.email, a.owner_id);
  Alcotest.(check error_list)
    "unique"
    [ ("email", "has already been taken") ]
    (invalid (insert [ ("email", "a@x.org"); ("age", "31") ]));
  Alcotest.(check error_list)
    "foreign key"
    [ ("owner_id", "does not exist") ]
    (invalid
       (insert [ ("email", "b@x.org"); ("age", "31"); ("owner_id", "99") ]));
  (* Past validation, so the database's CHECK refuses it. *)
  let unchecked =
    C.(
      for_insert Signups.table
      |> put Signups.email "c@x.org"
      |> put Signups.age (-5))
  in
  Alcotest.(check error_list)
    "check"
    [ ("age", "is invalid") ]
    (invalid (Blocking.insert_changeset db (with_constraints unchecked)));
  (* Not declared: the database's error as it was. *)
  (match
     Blocking.insert_changeset db
       C.(
         for_insert Signups.table
         |> put Signups.email "a@x.org"
         |> put Signups.age 1)
   with
  | Error (#Caqti_error.t as e) ->
      Alcotest.(check bool)
        "undeclared stays a Caqti error" true (is_unique_violation e)
  | _ -> Alcotest.fail "expected a Caqti error");
  let count () = ok (Blocking.count db (from Signups.table)) in
  Alcotest.(check error_list)
    "invalid is never sent"
    [ ("age", "is invalid") ]
    (invalid (insert [ ("email", "d@x.org"); ("age", "old") ]));
  Alcotest.(check int) "one account" 1 (count ());
  (* Updates. *)
  let update params =
    Blocking.update_changeset db
      (with_constraints
         (signup_changeset (C.for_update Signups.table a) params))
  in
  (match update [ ("age", "40"); ("owner_id", "") ] with
  | Ok a' ->
      Alcotest.(check (pair int (option int)))
        "updated" (40, None) (a'.age, a'.owner_id)
  | Error _ -> Alcotest.fail "update");
  (match update [ ("email", "a@x.org") ] with
  | Ok a' -> Alcotest.(check int) "no change, nothing sent" 30 a'.age
  | Error _ -> Alcotest.fail "no-op update");
  ignore (insert [ ("email", "e@x.org"); ("age", "1") ]);
  Alcotest.(check error_list)
    "update into a duplicate"
    [ ("email", "has already been taken") ]
    (invalid (update [ ("email", "e@x.org") ]));
  ok (from Signups.table |> where Ops.(Signups.id = a.id) |> Blocking.delete db);
  (match update [ ("age", "41") ] with
  | Error `Stale -> ()
  | _ -> Alcotest.fail "expected `Stale");
  Alcotest.check_raises "insert of an update"
    (Invalid_argument
       "Qb.insert_changeset: the changeset is for_update; use update_changeset")
    (fun () ->
      ignore (Blocking.insert_changeset db (C.for_update Signups.table a)))

(* Concurrent threads sharing the statement cache and transaction guard. *)
let test_concurrent_threads () =
  let worker i =
    let db = ok (Caqti_blocking.connect (Uri.of_string "sqlite3::memory:")) in
    let (module Db : DB) = db in
    Fun.protect ~finally:Db.disconnect @@ fun () ->
    ok (Blocking.create_table db Users.table);
    for j = 1 to 25 do
      ok
        (Blocking.transaction db (fun () ->
             let _ =
               ok
                 (Blocking.insert_values db
                    (values Users.table
                       Ops.
                         [
                           Users.name := Printf.sprintf "u%d_%d" i j;
                           Users.age := j;
                         ]))
             in
             let _ =
               ok
                 (from Users.table
                 |> where Ops.(Users.age >= 1)
                 |> Blocking.all db)
             in
             Ok ()))
    done;
    Alcotest.(check int)
      "all rows inserted" 25
      (ok (from Users.table |> Blocking.count db))
  in
  let threads = List.init 4 (fun i -> Thread.create worker i) in
  List.iter Thread.join threads

