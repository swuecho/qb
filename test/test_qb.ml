(* Statements written as SQL: parameters in, rows out. *)
let test_stmt db =
  seed db;
  let older_than age : (int * string) stmt =
    Stmt.(
      make "SELECT id, name FROM users WHERE age > $1 ORDER BY id"
        [ arg int age ]
        (both (ret int) (ret text)))
  in
  Alcotest.(check (list (pair int string)))
    "fetch_all"
    [ (1, "Ann"); (2, "Bob") ]
    (ok (Blocking.fetch_all db (older_than 18)));
  let named name =
    Stmt.(
      make "SELECT * FROM users WHERE name = $1"
        [ arg text name ]
        (whole Users.table))
  in
  Alcotest.(check bool)
    "fetch_opt, a whole row" true
    (ok (Blocking.fetch_opt db (named "Cy")) = Some cy);
  Alcotest.(check bool)
    "fetch_opt, no row" true
    (ok (Blocking.fetch_opt db (named "Di")) = None);
  let count = Stmt.(make "SELECT count(*) FROM users" [] (ret int)) in
  Alcotest.(check int) "fetch_one" 3 (ok (Blocking.fetch_one db count));
  (* let+ / and+ build a record or tuple; a name used twice is one $n. *)
  let emails =
    Stmt.(
      make "SELECT name, email FROM users WHERE age > $1 OR id = $1 ORDER BY id"
        [ arg int 40 ]
        (let+ name = ret text and+ email = ret (nullable text) in
         (name, email)))
  in
  Alcotest.(check (list (pair string (option string))))
    "let+"
    [ ("Bob", None) ]
    (ok (Blocking.fetch_all db emails));
  (* A list is spelled out and what follows renumbered; $1 comes twice. *)
  let named names min_age =
    Stmt.(
      make
        "SELECT name FROM users WHERE age > $1 AND name IN ($2) AND age > $3 \
         AND id >= $1 - $1 ORDER BY id"
        [ arg int 0; arg_list text names; arg int min_age ]
        (ret text))
  in
  Alcotest.(check string)
    "renumbered"
    "SELECT name FROM users WHERE age > $1 AND name IN ($2, $3, $4) AND age > \
     $5 AND id >= $1 - $1 ORDER BY id"
    (stmt_sql (named [ "Ann"; "Cy"; "Di" ] 18));
  Alcotest.(check (list string))
    "a list" [ "Ann" ]
    (ok (Blocking.fetch_all db (named [ "Ann"; "Cy"; "Di" ] 18)));
  Alcotest.(check (list string))
    "an empty list matches nothing" []
    (ok (Blocking.fetch_all db (named [] 18)));
  let others names =
    Stmt.(
      make "SELECT name FROM users WHERE name NOT IN ($1) ORDER BY id"
        [ arg_list text names ]
        (ret text))
  in
  Alcotest.(check (list string))
    "NOT IN an empty list matches everything" [ "Ann"; "Bob"; "Cy" ]
    (ok (Blocking.fetch_all db (others [])));
  Alcotest.(check (list string))
    "NOT IN" [ "Bob" ]
    (ok (Blocking.fetch_all db (others [ "Ann"; "Cy" ])));
  ok
