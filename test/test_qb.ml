let thing =
  Alcotest.testable
    (fun ppf (t : Things.t) ->
      Format.fprintf ppf "{%d %Ld %h %b %S %a %a %s %s}" t.id t.big t.ratio
        t.flag t.blob (Ptime.pp_rfc3339 ()) t.at (Ptime.pp_rfc3339 ()) t.day
        t.uid t.doc)
    (fun a b ->
      a.id = b.id && a.big = b.big && a.ratio = b.ratio && a.flag = b.flag
      && a.blob = b.blob && Ptime.equal a.at b.at && Ptime.equal a.day b.day
      && a.uid = b.uid && a.doc = b.doc)

let ok = function Ok x -> x | Error e -> Alcotest.fail (Caqti_error.show e)

(* ---------- SQL rendering ---------- *)

let check_sql name expected q = Alcotest.(check string) name expected (to_sql q)

let test_ddl () =
  let check dialect expected =
    Alcotest.(check string)
      "create table" expected
      (create_table_sql ~dialect Users.table)
  in
  check Postgres
    {|CREATE TABLE "users" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "name" TEXT NOT NULL, "age" BIGINT NOT NULL, "email" TEXT)|};
  check Sqlite
    {|CREATE TABLE "users" ("id" INTEGER PRIMARY KEY, "name" TEXT NOT NULL, "age" INTEGER NOT NULL, "email" TEXT)|};
  check Mysql
    "CREATE TABLE `users` (`id` BIGINT AUTO_INCREMENT PRIMARY KEY, `name` TEXT \
     NOT NULL, `age` BIGINT NOT NULL, `email` TEXT)"

let test_quoting () =
  let odd = column {|say "hi"|} text Fun.id in
  let odd_table = table "a`b" (col odd) in
  Alcotest.(check string)
    "postgres doubles quotes" {|SELECT "say ""hi""" FROM "a`b"|}
    (to_sql (from odd_table));
  Alcotest.(check string)
    "mysql doubles backticks" "SELECT `say \"hi\"` FROM `a``b`"
    (to_sql ~dialect:Mysql (from odd_table))

