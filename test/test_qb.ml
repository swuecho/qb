(* What the log says of each statement, without the time it took. *)
let test_log db =
  seed db;
  let lines = ref [] in
  let reporter =
    {
      Logs.report =
        (fun source _level ~over k msgf ->
          msgf (fun ?header:_ ?tags:_ fmt ->
              Format.kasprintf
                (fun line ->
                  (* Caqti logs on sources of its own. *)
                  if Logs.Src.equal source src then lines := line :: !lines;
                  over ();
                  k ())
                fmt));
    }
  in
  let before = Logs.reporter () and level = Logs.Src.level src in
  Logs.set_reporter reporter;
  Logs.Src.set_level src (Some Logs.Debug);
  Fun.protect
    ~finally:(fun () ->
      Logs.set_reporter before;
      Logs.Src.set_level src level)
    (fun () ->
      ignore
        (ok
           (from Users.table |> select [ Users.id ]
           |> where Ops.(Users.age > 18 && like_opt Users.email "%@x.org")
           |> Blocking.all db));
      ignore
        (ok (from Users.table |> where Ops.(Users.id = 9) |> Blocking.first db));
      ignore (ok (Blocking.count db (from Users.table)));
      ignore
        (ok
           (Blocking.update_count db
              Ops.[ Users.email := None ]
              (from Users.table |> where Ops.(Users.age < 60))));
      ok (Blocking.delete db (from Users.table |> where Ops.(Users.id = 3)));
      (match Blocking.insert db Users.table ann with
      | Ok () -> Alcotest.fail "a duplicate key was accepted"
      | Error _ -> ());
      ignore
        (ok
           (Blocking.fetch_all db
              (Stmt.make {|SELECT "name" FROM "users" WHERE "name" = $1|}
                 [ Stmt.arg text (String.make 200 'x') ]
                 (Stmt.ret text))));
      ignore
        (ok
           (Blocking.fetch_opt db
              (Stmt.make ~name:"by_name"
                 {|SELECT "name" FROM "users" WHERE "name" = $1|}
                 [ Stmt.arg text "Ann" ]
                 (Stmt.ret text)))));
  (* "..., 412us" and what the driver says of a failure are left out. *)
  let outcome line =
    match String.rindex_opt line ',' with
    | Some i -> String.sub line 0 i
    | None -> line
  in
  let failed line =
    match String.index_opt line ':' with
    | Some i when i > 9 && String.sub line (i - 6) 6 = "failed" ->
        String.sub line 0 i
    | _ -> outcome line
  in
  Alcotest.(check (list string))
    "one line each: text, parameters, outcome"
    [
      {|SELECT "id" FROM "users" WHERE ("age" > ? AND "email" LIKE ?) [18, "%@x.org"] -> 1 row|};
      {|SELECT "id", "name", "age", "email" FROM "users" WHERE "id" = ? LIMIT 1 [9] -> no row|};
      {|SELECT COUNT(*) FROM "users" -> 3|};
      {|UPDATE "users" SET "email" = ? WHERE "age" < ? [NULL, 60] -> 3 rows changed|};
      {|DELETE FROM "users" WHERE "id" = ? [3] -> done|};
      {|INSERT INTO "users" ("id", "name", "age", "email") VALUES (?, ?, ?, ?) [1, "Ann", 34, "ann@x.org"] -> failed|};
      {|SELECT "name" FROM "users" WHERE "name" = $1 ["|} ^ String.make 76 'x'
      ^ {|...] -> 0 rows|};
      {|[by_name] SELECT "name" FROM "users" WHERE "name" = $1 ["Ann"] -> 1 row|};
    ]
    (List.rev_map failed !lines);
  lines := [];
  ignore (ok (Blocking.count db (from Users.table)));
  Alcotest.(check int) "nothing below debug level" 0 (List.length !lines)

