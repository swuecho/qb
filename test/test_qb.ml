let create_signups ((module Db : DB) as db) =
  let sql =
    match Caqti_driver_info.dialect_tag Db.driver_info with
    | `Pgsql ->
        {|CREATE TABLE signups (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email TEXT NOT NULL UNIQUE,
            age BIGINT NOT NULL CHECK (age >= 0),
            owner_id BIGINT REFERENCES users (id))|}
    | _ ->
        ok
          (Db.exec
             Caqti_request.Infix.(
               (Caqti_type.unit ->. Caqti_type.unit) "PRAGMA foreign_keys = ON")
             ());
        {|CREATE TABLE signups (
            id INTEGER PRIMARY KEY,
            email TEXT NOT NULL UNIQUE,
            age INTEGER NOT NULL CONSTRAINT signups_age_check CHECK (age >= 0),
            owner_id INTEGER REFERENCES users (id))|}
  in
  ok
    (Db.exec Caqti_request.Infix.((Caqti_type.unit ->. Caqti_type.unit) sql) ());
  ignore db

let test_changeset_db db =
  seed db;
  create_signups db;
  let with_constraints cs =
    C.(
      cs
      |> unique_constraint Signups.email
      |> check_constraint Signups.age
      |> foreign_key_constraint Signups.owner_id)
  in
  let insert params =
    Blocking.insert_changeset db
      (with_constraints (signup_changeset (C.for_insert Signups.table) params))
  in
  let invalid = function
    | Error (`Invalid cs) -> errors cs
    | Ok _ -> Alcotest.fail "expected `Invalid, got Ok"
    | Error `Stale -> Alcotest.fail "expected `Invalid, got `Stale"
    | Error (#Caqti_error.t as e) -> Alcotest.fail (Caqti_error.show e)
  in
  let a =
    match insert [ ("email", "a@x.org"); ("age", "30"); ("owner_id", "1") ] with
    | Ok a -> a
    | Error _ -> Alcotest.fail "insert"
  in
  Alcotest.(check (pair string (option int)))
    "inserted, id filled in" ("a@x.org", Some 1) (a.email, a.owner_id);
  Alcotest.(check error_list)
    "unique"
    [ ("email", "has already been taken") ]
    (invalid (insert [ ("email", "a@x.org"); ("age", "31") ]));
  (* Primary-key duplicate matched via unique_constraint on both SQLite and
     Postgres. *)
  Alcotest.(check error_list)
    "primary key unique constraint"
    [ ("id", "has already been taken") ]
    (invalid
       (Blocking.insert_changeset db
          C.(
            for_insert Users.table |> put Users.id 1 |> put Users.name "Dup"
            |> put Users.age 20
            |> unique_constraint ~name:"users_pkey" Users.id)));
  Alcotest.(check error_list)
    "foreign key"
    [ ("owner_id", "does not exist") ]
    (invalid
       (insert [ ("email", "b@x.org"); ("age", "31"); ("owner_id", "99") ]));
  (* Past validation, so the database's CHECK refuses it. *)
  let unchecked =
    C.(
      for_insert Signups.table
      |> put Signups.email "c@x.org"
      |> put Signups.age (-5))
  in
  Alcotest.(check error_list)
    "check"
    [ ("age", "is invalid") ]
    (invalid (Blocking.insert_changeset db (with_constraints unchecked)));
  (* Not declared: the database's error as it was. *)
  (match
     Blocking.insert_changeset db
       C.(
         for_insert Signups.table
         |> put Signups.email "a@x.org"
         |> put Signups.age 1)
   with
  | Error (#Caqti_error.t as e) ->
      Alcotest.(check bool)
        "undeclared stays a Caqti error" true (is_unique_violation e)
  | _ -> Alcotest.fail "expected a Caqti error");
  let count () = ok (Blocking.count db (from Signups.table)) in
  Alcotest.(check error_list)
    "invalid is never sent"
    [ ("age", "is invalid") ]
    (invalid (insert [ ("email", "d@x.org"); ("age", "old") ]));
  Alcotest.(check int) "one account" 1 (count ());
  (* Updates. *)
  let update params =
    Blocking.update_changeset db
      (with_constraints
         (signup_changeset (C.for_update Signups.table a) params))
  in
  (match update [ ("age", "40"); ("owner_id", "") ] with
  | Ok a' ->
      Alcotest.(check (pair int (option int)))
        "updated" (40, None) (a'.age, a'.owner_id)
  | Error _ -> Alcotest.fail "update");
  (match update [ ("email", "a@x.org") ] with
  | Ok a' -> Alcotest.(check int) "no change, nothing sent" 30 a'.age
  | Error _ -> Alcotest.fail "no-op update");
  ignore (insert [ ("email", "e@x.org"); ("age", "1") ]);
  Alcotest.(check error_list)
    "update into a duplicate"
    [ ("email", "has already been taken") ]
    (invalid (update [ ("email", "e@x.org") ]));
  ok (from Signups.table |> where Ops.(Signups.id = a.id) |> Blocking.delete db);
  (match update [ ("age", "41") ] with
  | Error `Stale -> ()
  | _ -> Alcotest.fail "expected `Stale");
  Alcotest.check_raises "insert of an update"
    (Invalid_argument
       "Qb.insert_changeset: the changeset is for_update; use update_changeset")
    (fun () ->
      ignore (Blocking.insert_changeset db (C.for_update Signups.table a)))

(* Concurrent threads sharing the statement cache and transaction guard. *)
let test_concurrent_threads () =
  let worker i =
    let db = ok (Caqti_blocking.connect (Uri.of_string "sqlite3::memory:")) in
    let (module Db : DB) = db in
    Fun.protect ~finally:Db.disconnect @@ fun () ->
    ok (Blocking.create_table db Users.table);
    for j = 1 to 25 do
      ok
        (Blocking.transaction db (fun () ->
             let _ =
               ok
                 (Blocking.insert_values db
                    (values Users.table
                       Ops.
                         [
                           Users.name := Printf.sprintf "u%d_%d" i j;
                           Users.age := j;
                         ]))
             in
             let _ =
               ok
                 (from Users.table
                 |> where Ops.(Users.age >= 1)
                 |> Blocking.all db)
             in
             Ok ()))
    done;
    Alcotest.(check int)
      "all rows inserted" 25
      (ok (from Users.table |> Blocking.count db))
  in
  let threads = List.init 4 (fun i -> Thread.create worker i) in
  List.iter Thread.join threads

(* ---------- multi-table query builder, expressions, CTEs, relations ---------- *)

let test_multi_sql () =
  (* 3-table join with left_join and self-join *)
  let q3 =
    Query.(
      build
        (let* u = from Users.table in
         let* c =
           join Comments.table ~on:(fun c ->
               Expr.Ops.(c.@(Comments.author_id) = u.@(Users.id)))
         in
         let* parent =
           left_join Comments.table ~on:(fun p ->
               Expr.Ops.(c.@(Comments.reply_to) =? p.@(Comments.id)))
         in
         let* () =
           where
             Expr.Ops.(
               u.@(Users.age) >= Expr.int 18
               && is_null parent.@??(Comments.reply_to))
         in
         let* () =
           order_by [ desc c.@(Comments.id); nulls_last (asc u.@(Users.name)) ]
         in
         let* () = limit 10 in
         let* () = offset 5 in
         select
           (let+ uname = expr u.@(Users.name)
            and+ body = expr c.@(Comments.body)
            and+ pbody = expr parent.@?(Comments.body) in
            (uname, body, pbody))))
  in
  Alcotest.(check string)
    "3-table join postgres"
    {|SELECT "t0"."name", "t1"."body", "t2"."body" FROM "users" AS "t0" INNER JOIN "comments" AS "t1" ON "t1"."author_id" = "t0"."id" LEFT JOIN "comments" AS "t2" ON "t1"."reply_to" = "t2"."id" WHERE ("t0"."age" >= ? AND "t2"."reply_to" IS NULL) ORDER BY "t1"."id" DESC, "t0"."name" ASC NULLS LAST LIMIT 10 OFFSET 5|}
    (Query.to_sql ~dialect:Postgres q3);
  (* Dialect differences: concat, length, sum, avg, lock *)
  let q_exprs =
    Query.(
      build
        (let* u = from Users.table in
         let* () = group_by [ Expr.any u.@(Users.name) ] in
         let* () = having Expr.Ops.(Expr.count_all > Expr.int 1) in
         let* () = for_update ~skip_locked:true () in
         select
           (let+ label =
              expr Expr.Ops.(Expr.lower u.@(Users.name) ^ Expr.text "!")
            and+ len = expr (Expr.length u.@(Users.name))
            and+ total_age = expr (Expr.sum_int u.@(Users.age))
            and+ avg_age = expr (Expr.avg u.@(Users.age)) in
            (label, len, total_age, avg_age))))
  in
  Alcotest.(check string)
    "exprs postgres"
    {|SELECT (LOWER("t0"."name") || ?), CHAR_LENGTH("t0"."name"), CAST(SUM("t0"."age") AS BIGINT), CAST(AVG("t0"."age") AS DOUBLE PRECISION) FROM "users" AS "t0" GROUP BY "t0"."name" HAVING COUNT(*) > ? FOR UPDATE SKIP LOCKED|}
    (Query.to_sql ~dialect:Postgres q_exprs);
  Alcotest.(check string)
    "exprs mysql"
    {|SELECT CONCAT(LOWER(`t0`.`name`), ?), CHAR_LENGTH(`t0`.`name`), SUM(`t0`.`age`), CAST(AVG(`t0`.`age`) AS DOUBLE) FROM `users` AS `t0` GROUP BY `t0`.`name` HAVING COUNT(*) > ? FOR UPDATE SKIP LOCKED|}
    (Query.to_sql ~dialect:Mysql q_exprs);
  Alcotest.(check string)
    "exprs sqlite"
    {|SELECT (LOWER("t0"."name") || ?), LENGTH("t0"."name"), SUM("t0"."age"), CAST(AVG("t0"."age") AS REAL) FROM "users" AS "t0" GROUP BY "t0"."name" HAVING COUNT(*) > ?|}
    (Query.to_sql ~dialect:Sqlite q_exprs);
  Alcotest.(check string)
    "grouped count wraps subquery and strips FOR UPDATE"
    {|SELECT COUNT(*) FROM (SELECT (LOWER("t0"."name") || ?), CHAR_LENGTH("t0"."name"), CAST(SUM("t0"."age") AS BIGINT), CAST(AVG("t0"."age") AS DOUBLE PRECISION) FROM "users" AS "t0" GROUP BY "t0"."name" HAVING COUNT(*) > ?) AS "_qb_count"|}
    (Query.count_sql ~dialect:Postgres q_exprs);
  (* right_join & full_join rebind left handle as nullable *)
  let q_right =
    Query.(
      build
        (let* u = from Users.table in
         let* u, c =
           right_join u Comments.table ~on:(fun c ->
               Expr.Ops.(c.@(Comments.author_id) = u.@(Users.id)))
         in
         select
           (let+ uname = expr u.@?(Users.name)
            and+ body = expr c.@(Comments.body) in
            (uname, body))))
  in
  Alcotest.(check string)
    "right_join sql"
    {|SELECT "t0"."name", "t1"."body" FROM "users" AS "t0" RIGHT JOIN "comments" AS "t1" ON "t1"."author_id" = "t0"."id"|}
    (Query.to_sql ~dialect:Postgres q_right);
  let q_full =
    Query.(
      build
        (let* u = from Users.table in
         let* u, c =
           full_join u Comments.table ~on:(fun c ->
               Expr.Ops.(c.@(Comments.author_id) = u.@(Users.id)))
         in
         select
           (let+ uname = expr u.@?(Users.name)
            and+ body = expr c.@?(Comments.body) in
            (uname, body))))
  in
  Alcotest.(check string)
    "full_join sql"
    {|SELECT "t0"."name", "t1"."body" FROM "users" AS "t0" FULL JOIN "comments" AS "t1" ON "t1"."author_id" = "t0"."id"|}
    (Query.to_sql ~dialect:Postgres q_full);
  (* CTE + derived table *)
  let q_cte =
    Query.(
      build
        (let* stats, (author_id, total) =
           with_cte "comment_stats"
             (let* c = from Comments.table in
              let* () = group_by [ Expr.any c.@(Comments.author_id) ] in
              select_named
                Named.(
                  let+ aid = field "author_id" c.@(Comments.author_id)
                  and+ cnt = field "total" Expr.count_all in
                  (aid, cnt)))
         in
         let* u = from Users.table in
         let* s =
           left_join_cte stats ~on:(fun s ->
               Expr.Ops.(s.@(author_id) = u.@(Users.id)))
         in
         select
           (let+ name = expr u.@(Users.name)
            and+ total = expr (Expr.coalesce s.@?(total) (Expr.int 0)) in
            (name, total))))
  in
  Alcotest.(check string)
    "cte sql"
    {|WITH "comment_stats" AS (SELECT "t2"."author_id" AS "author_id", COUNT(*) AS "total" FROM "comments" AS "t2" GROUP BY "t2"."author_id") SELECT "t0"."name", COALESCE("t1"."total", ?) FROM "users" AS "t0" LEFT JOIN "comment_stats" AS "t1" ON "t1"."author_id" = "t0"."id"|}
    (Query.to_sql ~dialect:Postgres q_cte);
  (* Correlated EXISTS *)
  let q_exists =
    Query.(
      build
        (let* u = from Users.table in
         let* () =
           where
             (exists
                (sub
                   (let* c = from Comments.table in
                    where Expr.Ops.(c.@(Comments.author_id) = u.@(Users.id)))))
         in
         select (expr u.@(Users.name))))
  in
  Alcotest.(check string)
    "correlated exists"
    {|SELECT "t0"."name" FROM "users" AS "t0" WHERE EXISTS (SELECT 1 FROM "comments" AS "t1" WHERE "t1"."author_id" = "t0"."id")|}
    (Query.to_sql ~dialect:Postgres q_exists);
  (* Expression update and upsert *)
  let upd_sql =
    from Users.table
    |> where Ops.(Users.id = 1)
    |> update_sql
         [
           set_expr Users.age Expr.Ops.(Expr.col Users.age + Expr.int 1);
           set_expr Users.name (Expr.trim (Expr.col Users.name));
         ]
  in
  Alcotest.(check string)
    "set_expr update"
    {|UPDATE "users" SET "age" = ("age" + ?), "name" = TRIM("name") WHERE "id" = ?|}
    upd_sql;
  let ups_sql =
    upsert_sql
      On_conflict.(
        do_update
          ~target:[ col Users.id ]
          ~set:
            [
              set_expr Users.age
                Expr.Ops.(Expr.col Users.age + Expr.excluded Users.age);
            ]
          ())
      (values Users.table
         Ops.[ Users.id := 1; Users.name := "Ann"; Users.age := 5 ])
  in
  Alcotest.(check string)
    "set_expr upsert"
    {|INSERT INTO "users" ("id", "name", "age") VALUES (?, ?, ?) ON CONFLICT ("id") DO UPDATE SET "age" = ("users"."age" + EXCLUDED."age") RETURNING "id", "name", "age", "email"|}
    ups_sql;
  (* Multi-table update_from & delete_using *)
  let upd_from =
    Query.(
      update_from Users.table (fun u ->
          let* c = from Comments.table in
          let* () =
            where
              Expr.Ops.(
                c.@(Comments.author_id) = u.@(Users.id)
                && c.@(Comments.body) = Expr.text "promote")
          in
          return [ set Users.age Expr.Ops.(u.@(Users.age) + Expr.int 1) ]))
  in
  Alcotest.(check string)
    "update_from sql"
    {|UPDATE "users" AS "t0" SET "age" = ("t0"."age" + ?) FROM "comments" AS "t1" WHERE ("t1"."author_id" = "t0"."id" AND "t1"."body" = ?)|}
    (Query.update_from_sql ~dialect:Postgres upd_from);
  let del_using =
    Query.(
      delete_using Comments.table (fun c ->
          let* u = from Users.table in
          where
            Expr.Ops.(
              u.@(Users.id) = c.@(Comments.author_id)
              && u.@(Users.age) < Expr.int 18)))
  in
  Alcotest.(check string)
    "delete_using sql"
    {|DELETE FROM "comments" AS "t0" USING "users" AS "t1" WHERE ("t1"."id" = "t0"."author_id" AND "t1"."age" < ?)|}
    (Query.delete_using_sql ~dialect:Postgres del_using);
  Alcotest.check_raises "update_from requires where"
    (Invalid_argument
       "Qb.Query.update_from: missing where (pass ~all_rows:true to update \
        every row)") (fun () ->
      ignore
        (Query.update_from Users.table (fun _ ->
             Query.return [ Query.set_val Users.age 0 ])));
  Alcotest.check_raises "delete_using requires where"
    (Invalid_argument
       "Qb.Query.delete_using: missing where (pass ~all_rows:true to delete \
