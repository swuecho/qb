(* The runner, against Postgres when QB_TEST_PG_URL is set (see
   scripts/test-pg.sh); reading, splitting and embedding without one. *)

open Qb_migrate

let m name sql = { name; sql }

let init =
  m "001_init.sql"
    "CREATE TABLE authors (\n\
    \  id BIGSERIAL PRIMARY KEY,\n\
    \  name TEXT NOT NULL,\n\
    \  country TEXT\n\
     );\n\
     -- a semicolon; in a comment\n\
     INSERT INTO authors (name) VALUES ('semi;colon');\n"

let books =
  m "002_books.sql"
    "CREATE TABLE books (id BIGSERIAL PRIMARY KEY, author_id BIGINT NOT NULL \
     REFERENCES authors (id), title VARCHAR(80) NOT NULL, tags TEXT[]);"

let strings = Alcotest.(check (list string))

(* ---------- without a database ---------- *)

let test_of_dir () =
  let dir = Filename.temp_file "qb_migrate" "" in
  Sys.remove dir;
  Sys.mkdir dir 0o700;
  let write name text =
    Out_channel.with_open_bin (Filename.concat dir name) (fun oc ->
        output_string oc text)
  in
  write "002_b.sql" "SELECT 2";
  write "001_a.sql" "SELECT 1";
  write "notes.txt" "not a migration";
  (match of_dir dir with
  | Ok ms ->
      strings "in name order, .sql only"
        [ "001_a.sql"; "002_b.sql" ]
        (List.map (fun m -> m.name) ms);
      strings "with their text" [ "SELECT 1"; "SELECT 2" ]
        (List.map (fun m -> m.sql) ms)
  | Error e -> Alcotest.fail e);
  Alcotest.(check bool)
    "a folder that isn't there" true
    (Result.is_error (of_dir (Filename.concat dir "nope")))

let test_split () =
  match
    Qb_pg_parse.Pg.split
      "SELECT 1; -- one;\n\
       CREATE FUNCTION f() RETURNS int AS $$ SELECT 1; $$ LANGUAGE sql;\n\
       SELECT ';'"
  with
  | Error e -> Alcotest.fail e.message
  | Ok stmts ->
      strings "a ; in a comment, a body or a string doesn't split"
        [
          "SELECT 1";
          "CREATE FUNCTION f() RETURNS int AS $$ SELECT 1; $$ LANGUAGE sql";
          "SELECT ';'";
        ]
        stmts

let test_embed () =
  Alcotest.(check string)
    "an OCaml list"
    "(* Generated by qb-migrate embed. Do not edit. *)\n\n\
     let migrations : Qb_migrate.migration list =\n\
    \  [\n\
    \    { name = \"001_a.sql\"; sql = {sql|SELECT 1|sql} };\n\
    \    { name = \"002_b.sql\"; sql = {sql1|SELECT '|sql}'|sql1} };\n\
    \  ]\n"
    (embed [ m "001_a.sql" "SELECT 1"; m "002_b.sql" "SELECT '|sql}'" ])

(* ---------- against Postgres ---------- *)

module type DB = Caqti_blocking.CONNECTION

let ok = function Ok x -> x | Error e -> Alcotest.fail (error_to_string e)
let caqti = function Ok x -> x | Error e -> Alcotest.fail (Caqti_error.show e)

let exec (module Db : DB) sql =
  caqti
    (Db.exec
       (Caqti_request.create ~oneshot:true Caqti_type.unit Caqti_type.unit
          Caqti_mult.zero (fun _ -> Caqti_query.L sql))
       ())

let has_table (module Db : DB) name =
  caqti
    (Db.find
       (Caqti_request.Infix.(Caqti_type.string ->! Caqti_type.bool)
          "SELECT to_regclass(?) IS NOT NULL")
       name)

(* A schema of its own, emptied for each test: other suites use the same
   database at the same time. *)
let with_db url f () =
  let db = caqti (Caqti_blocking.connect (Uri.of_string url)) in
  let (module Db : DB) = db in
  Fun.protect ~finally:Db.disconnect @@ fun () ->
  List.iter (exec db)
    [
      "DROP SCHEMA IF EXISTS qb_migrate_test CASCADE";
      "CREATE SCHEMA qb_migrate_test";
      "SET search_path TO qb_migrate_test";
    ];
  f db

let names db ms =
  List.map
    (fun (n, s) ->
      n ^ ": "
      ^
      match s with
      | Applied _ -> "applied"
      | Pending -> "pending"
      | Changed _ -> "changed"
      | Missing _ -> "missing")
    (ok (status db ms))

let test_run db =
  strings "status before, with no table yet"
    [ "001_init.sql: pending"; "002_books.sql: pending" ]
    (names db [ init; books ]);
  strings "applies in order"
    [ "001_init.sql"; "002_books.sql" ]
    (ok (run db [ init; books ]));
  strings "status after"
    [ "001_init.sql: applied"; "002_books.sql: applied" ]
    (names db [ init; books ]);
  strings "nothing the second time" [] (ok (run db [ init; books ]));
  strings "the database matches" [] (ok (verify db [ init; books ]));
  let more = m "003_more.sql" "CREATE TABLE more (x INT)" in
  strings "only what is pending" [ "003_more.sql" ]
    (ok (run db [ init; books; more ]));
  let dump =
    m "004_dump.sql"
      "SELECT pg_catalog.set_config('search_path', '', false);\n\
       CREATE TABLE qb_migrate_test.dumped (id INT);"
  in
  let after = m "005_after.sql" "CREATE TABLE after_dump (id INT)" in
  strings "pg_dump search_path reset still records and restores search_path"
    [ "004_dump.sql"; "005_after.sql" ]
    (ok (run db [ init; books; more; dump; after ]));
  strings "verify still passes after search_path reset" []
    (ok (verify db [ init; books; more; dump; after ]))

let test_refusals db =
  ignore (ok (run db [ init; books ]));
  let is name expected r =
    Alcotest.(check string)
      name expected
      (match r with
      | Ok _ -> "ok"
      | Error (`Changed n) -> "changed " ^ n
      | Error (`Missing n) -> "missing " ^ n
      | Error (`Out_of_order (p, a)) -> p ^ " before " ^ a
      | Error (`Invalid (n, _)) -> "invalid " ^ n
      | Error (`Failed (n, _)) -> "failed " ^ n
      | Error (`Not_verified _) -> "not verified"
      | Error (`Db e) -> Caqti_error.show e)
  in
  is "an applied migration was edited" "changed 001_init.sql"
    (run db [ { init with sql = init.sql ^ "\n-- edited" }; books ]);
  is "an applied migration is gone" "missing 001_init.sql" (run db [ books ]);
  strings "status says so too"
    [ "002_books.sql: applied"; "001_init.sql: missing" ]
    (names db [ books ]);
  let late = m "0015_late.sql" "CREATE TABLE late (x INT)" in
  is "a pending migration before an applied one"
    "0015_late.sql before 002_books.sql"
    (run db [ init; late; books ]);
  Alcotest.(check bool) "it wasn't applied" false (has_table db "late");
  is "allowed when asked" "ok" (run ~out_of_order:true db [ init; late; books ]);
  Alcotest.(check bool) "it was applied" true (has_table db "late")

let test_failures db =
  let good = m "001_good.sql" "CREATE TABLE good (x INT)" in
  let bad =
    m "002_bad.sql" "CREATE TABLE half (x INT);\nINSERT INTO nowhere VALUES (1)"
  in
  (match run db [ good; bad ] with
  | Error (`Failed ("002_bad.sql", message)) ->
      Alcotest.(check bool)
        "the message names the statement" true
        (let sub = "in: INSERT INTO nowhere VALUES (1)" in
         let n = String.length sub in
         let rec has i =
           i + n <= String.length message
           && (String.sub message i n = sub || has (i + 1))
         in
         has 0)
  | Ok _ -> Alcotest.fail "the bad migration was applied"
  | Error e -> Alcotest.fail (error_to_string e));
  Alcotest.(check bool) "the one before it stays" true (has_table db "good");
  Alcotest.(check bool) "its own work is undone" false (has_table db "half");
  strings "and it is still pending"
    [ "001_good.sql: applied"; "002_bad.sql: pending" ]
    (names db [ good; bad ]);
  let unparsable = m "003_typo.sql" "CREATE TABEL t (x INT)" in
  let fine = m "002_fine.sql" "CREATE TABLE fine (x INT)" in
  (match run db [ good; fine; unparsable ] with
  | Error (`Invalid ("003_typo.sql", _)) -> ()
  | Ok _ -> Alcotest.fail "the unparsable migration was applied"
  | Error e -> Alcotest.fail (error_to_string e));
  Alcotest.(check bool)
    "nothing runs when a later one can't be parsed" false (has_table db "fine");
  let own = m "002_own.sql" "BEGIN;\nCREATE TABLE own (x INT);\nCOMMIT;" in
  (match run db [ good; own ] with
  | Error (`Invalid ("002_own.sql", _)) -> ()
  | Ok _ -> Alcotest.fail "a migration with its own COMMIT was applied"
  | Error e -> Alcotest.fail (error_to_string e));
  Alcotest.(check bool)
    "its own BEGIN and COMMIT are refused" false (has_table db "own");
  strings "and allowed without a transaction" [ "002_own.sql" ]
    (ok
       (run db [ good; { own with sql = "-- qb:no-transaction\n" ^ own.sql } ]));
  exec db "DELETE FROM qb_migrations WHERE name = '002_own.sql'";
  let loose =
    m "002_loose.sql"
      "-- qb:no-transaction\n\
       CREATE TABLE kept (x INT);\n\
       INSERT INTO nowhere VALUES (1)"
  in
  (match run db [ good; loose ] with
  | Error (`Failed ("002_loose.sql", _)) -> ()
  | Ok _ -> Alcotest.fail "the failing migration was applied"
  | Error e -> Alcotest.fail (error_to_string e));
  Alcotest.(check bool)
    "without a transaction, what it did stays" true (has_table db "kept")

let test_verify db =
  ignore (ok (run db [ init; books ]));
  List.iter (exec db)
    [
      "ALTER TABLE authors DROP COLUMN country";
      "ALTER TABLE authors ADD COLUMN born INT";
      "ALTER TABLE authors ALTER COLUMN name DROP NOT NULL";
      "ALTER TABLE books ALTER COLUMN title TYPE TEXT";
      "ALTER TABLE books ALTER COLUMN tags SET NOT NULL";
      "CREATE TABLE stray (x INT)";
    ];
  strings "each difference"
    [
      "authors.name: NOT NULL in the migrations, nullable in the database";
      "authors.country: not in the database";
      "authors.born: not in the migrations";
      "books.title: VARCHAR(80) in the migrations, text in the database";
      "books.tags: nullable in the migrations, NOT NULL in the database";
      "table stray: not in the migrations";
    ]
    (ok (verify db [ init; books ]));
  strings "a table that was never created"
    [ "table more: not in the database"; "table stray: not in the migrations" ]
    (List.filter
       (fun d -> String.length d > 5 && String.sub d 0 5 = "table")
       (ok
          (verify db
             [ init; books; m "003_more.sql" "CREATE TABLE more (x INT)" ])))

(* Lengths, precisions, defaults and keys; and no difference found in a
   table of many types as it was migrated. *)
let test_verify_details db =
  let wide =
    m "001_wide.sql"
      {|CREATE TYPE mood AS ENUM ('ok', 'bad');
CREATE TABLE wide (
  id BIGSERIAL,
  code VARCHAR(10) NOT NULL,
  fixed CHAR(3),
  one CHAR,
  loose VARCHAR,
  amount NUMERIC(10, 2),
  whole NUMERIC(8),
  any_number NUMERIC,
  at TIMESTAMP(3),
  seen TIMESTAMPTZ NOT NULL DEFAULT now(),
  note TEXT DEFAULT 'x',
  n INT GENERATED ALWAYS AS IDENTITY,
  doubled INT GENERATED ALWAYS AS (n * 2) STORED,
  tags VARCHAR(5)[],
  m mood,
  "Mixed Case" TEXT,
  small SMALLINT, r REAL, d DOUBLE PRECISION, b BOOLEAN, j JSONB, u UUID,
  day DATE, raw BYTEA,
  PRIMARY KEY (id, code)
);|}
  in
  ignore (ok (run db [ wide ]));
  strings "as migrated, nothing differs" [] (ok (verify db [ wide ]));
  List.iter (exec db)
    [
      "ALTER TABLE wide ALTER COLUMN code TYPE VARCHAR(20)";
      "ALTER TABLE wide ALTER COLUMN fixed TYPE CHAR(4)";
      "ALTER TABLE wide ALTER COLUMN one TYPE CHAR(5)";
      "ALTER TABLE wide ALTER COLUMN loose TYPE VARCHAR(9)";
      "ALTER TABLE wide ALTER COLUMN amount TYPE NUMERIC(12, 2)";
      "ALTER TABLE wide ALTER COLUMN whole TYPE NUMERIC(8, 1)";
      "ALTER TABLE wide ALTER COLUMN any_number TYPE NUMERIC(6, 2)";
      "ALTER TABLE wide ALTER COLUMN at TYPE TIMESTAMP(6)";
      "ALTER TABLE wide ALTER COLUMN note DROP DEFAULT";
      "ALTER TABLE wide ALTER COLUMN small SET DEFAULT 1";
      "ALTER TABLE wide DROP CONSTRAINT wide_pkey";
      "ALTER TABLE wide ADD PRIMARY KEY (id)";
    ];
  strings "each difference"
    [
      "wide.code: VARCHAR(10) in the migrations, varchar(20) in the database";
      "wide.fixed: CHAR(3) in the migrations, bpchar(4) in the database";
      "wide.one: CHAR in the migrations, bpchar(5) in the database";
      "wide.loose: VARCHAR in the migrations, varchar(9) in the database";
      "wide.amount: NUMERIC(10,2) in the migrations, numeric(12,2) in the \
       database";
      "wide.whole: NUMERIC(8) in the migrations, numeric(8,1) in the database";
      "wide.any_number: NUMERIC in the migrations, numeric(6,2) in the database";
      "wide.at: TIMESTAMP(3) in the migrations, timestamp(6) in the database";
      "wide.note: a default in the migrations, none in the database";
      "wide.small: no default in the migrations, one in the database";
      "wide: primary key (id, code) in the migrations, (id) in the database";
    ]
    (ok (verify db [ wide ]));
  exec db "ALTER TABLE wide DROP CONSTRAINT wide_pkey";
  strings "no primary key at all"
    [ "wide: primary key (id, code) in the migrations, none in the database" ]
    (List.filter
       (fun d -> String.length d > 5 && String.sub d 0 5 = "wide:")
       (ok (verify db [ wide ])))

let test_baseline db =
  (* A database that has the schema and no record of how. *)
  ignore (ok (run db [ init; books ]));
  exec db "DROP TABLE qb_migrations";
  strings "nothing is recorded"
    [ "001_init.sql: pending"; "002_books.sql: pending" ]
    (names db [ init; books ]);
  let more = m "003_more.sql" "CREATE TABLE more (x INT)" in
  (match baseline db [ init; books; more ] with
  | Error (`Not_verified [ "table more: not in the database" ]) -> ()
  | Ok _ -> Alcotest.fail "recorded a migration the database doesn't have"
  | Error e -> Alcotest.fail (error_to_string e));
  strings "records them, running none"
    [ "001_init.sql"; "002_books.sql" ]
    (ok (baseline db [ init; books ]));
  strings "then only new ones run" [ "003_more.sql" ]
    (ok (run db [ init; books; more ]))

let () =
  let t name f = Alcotest.test_case name `Quick f in
  Alcotest.run "qb-migrate"
    [
      ( "files",
        [ t "of_dir" test_of_dir; t "split" test_split; t "embed" test_embed ]
      );
      ( "postgres",
        match Sys.getenv_opt "QB_TEST_PG_URL" with
        | Some url ->
            [
              t "run" (with_db url test_run);
              t "refusals" (with_db url test_refusals);
              t "failures" (with_db url test_failures);
              t "verify" (with_db url test_verify);
              t "verify, in detail" (with_db url test_verify_details);
              t "baseline" (with_db url test_baseline);
            ]
        | None -> [ t "set QB_TEST_PG_URL to run" (fun () -> Alcotest.skip ()) ]
      );
    ]
